import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { testEnvironment } from './test-environment.mjs';
import { runNode } from './helpers/environment.mjs';
const env=testEnvironment();
const root=path.resolve(os.tmpdir(),`restore-rehearsal-${Date.now()}`);
Object.assign(env,{BACKUP_DIR:path.join(root,'backups'),BACKUP_DB_USER:env.DB_USER,BACKUP_DB_PASSWORD:env.DB_PASSWORD,RESTORE_DB_USER:env.DB_USER,RESTORE_DB_PASSWORD:env.DB_PASSWORD,RESTORE_DB_NAME:`camisaria_${Date.now()}_restore_test`,RESTORE_UPLOADS_DIR:path.join(root,'restored-uploads')});
if(process.platform==='win32')Object.assign(env,{MYSQLDUMP_BIN:process.env.TEST_MYSQLDUMP_BIN||'C:/Program Files/MySQL/MySQL Server 8.0/bin/mysqldump.exe',MYSQL_BIN:process.env.TEST_MYSQL_BIN||'C:/Program Files/MySQL/MySQL Server 8.0/bin/mysql.exe'});
await fs.mkdir(env.UPLOADS_DIR,{recursive:true});
await fs.writeFile(path.join(env.UPLOADS_DIR,'restore-fixture.txt'),'Restoration fixture only.');
runNode(env,'ops/backup.mjs');
const restored=JSON.parse(runNode(env,'ops/restore-backup.mjs'));
assert.equal(restored.ok,true);
assert.equal(await fs.readFile(path.join(env.RESTORE_UPLOADS_DIR,'restore-fixture.txt'),'utf8'),'Restoration fixture only.');
await fs.mkdir('qa-evidence/structure',{recursive:true});
await fs.writeFile('qa-evidence/structure/restore.json',JSON.stringify({ok:true,targetDatabase:env.RESTORE_DB_NAME,comparisons:restored.comparisons,uploads:restored.uploads},null,2)+'\n');
console.log('✓ Backup e restauração em banco e diretório novos; contagens e arquivo conferidos.');
